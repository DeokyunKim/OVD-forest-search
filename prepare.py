#!/usr/bin/env python
"""Build ``datasets/v6_fp_fb/{train,val,test}.json`` and the statistics document.

Spec: the vocabulary specification §1/§5, the frozen-hyperparameter specification §4.0.

    $PY build_v6_dataset.py (research tree)

Nothing is written unless :func:`utils.data.dataset_build.verify_v6_json` passes
and the image census matches
:data:`utils.data.dataset_build.EXPECTED_IMAGES` for that split.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from utils.runner.logging_utils import get_logger  # noqa: E402
from utils.data.dataset_build import (  # noqa: E402
    EXPECTED_IMAGES,
    out_dir,
    sources,
    SplitReport,
    build_split,
    verify_v6_json,
    write_json,
)
from utils.protocol.vocabulary import (  # noqa: E402
    ETC_CATEGORY_ID,
    ETC_CATEGORY_NAME,
    FB_RENAME,
    FP_POSE_SUBCLASSES,
    V6_CAPTION,
    V6_CLASSES,
)

logger = get_logger(__name__)

#: Written beside the benchmark it describes. `outputs/` is where everything a
#: run produces goes, and unlike the documentation directory it is part of the
#: published tree -- a public clone had nowhere to put this file.
DOC_PATH = Path(__file__).resolve().parent / "outputs" / "v6_dataset_statistics.md"


def _table(rows: list[tuple[str, ...]], header: tuple[str, ...]) -> str:
    lines = ["| " + " | ".join(header) + " |",
             "|" + "|".join("---" for _ in header) + "|"]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def render_document(reports: dict[str, SplitReport]) -> str:
    """Render the split/class census and the before-after mapping table."""
    order = [s for s in ("train", "val", "test") if s in reports]

    census = _table(
        [(s, f"{reports[s].n_images:,}", f"{reports[s].n_annotations:,}",
          f"{reports[s].n_negative_images:,}",
          ", ".join(f"{k}={v:,}" for k, v in sorted(reports[s].source_image_counts.items())))
         for s in order],
        ("split", "images", "annotations", "negative (0-ann) images", "images by source"),
    )

    class_rows = []
    for name in (*V6_CLASSES, ETC_CATEGORY_NAME):
        class_rows.append((name,
                           *(f"{reports[s].class_distribution.get(name, 0):,}" for s in order)))
    class_tbl = _table(class_rows, ("V6 class", *order))

    # Before/after mapping: every source category name -> its V6 destination.
    dest = {}
    for pose in FP_POSE_SUBCLASSES:
        dest[f"ForestPersons `{pose}`"] = "`person`"
    for src in sorted(FB_RENAME):
        dest[f"ForestBelongings `{src}`"] = f"`{FB_RENAME[src]}`"
    for keep in ("person", "hat", "bag"):
        dest[f"ForestBelongings `{keep}`"] = f"`{keep}` (unchanged)"
    dest["ForestBelongings `etc`"] = f"`etc` id {ETC_CATEGORY_ID}, `iscrowd=1` ignore (not in V6)"

    pre_rows = []
    for label, target in dest.items():
        counts = []
        for s in order:
            key_src = "fp" if "ForestPersons " in label else "fb"
            raw = label.split("`")[1]
            counts.append(f"{reports[s].pre_mapping_distribution.get(f'{key_src}:{raw}', 0):,}")
        pre_rows.append((label, target, *counts))
    map_tbl = _table(pre_rows, ("source category", "V6 destination", *(f"{s} (source count)" for s in order)))

    return f"""# V6 dataset census — `datasets/v6_fp_fb/`

Generated by `build_v6_dataset.py (research tree)`. Every number below is read from
the built json files, not from any pre-2026-08-08 artefact.

Spec: `the vocabulary specification` §1/§5, `the frozen-hyperparameter specification` §4.0.

Query caption (V6, spec order): `{V6_CAPTION}`

## 1. Split census

{census}

Negative (zero-annotation) images are **kept**. Spec §4.0 forbids removing
images for class balancing and forbids difficulty filtering, so the negative
count is reported and not acted on. ForestPersonsIR is excluded from every
split (user decision 3, 2026-08-08).

## 2. Annotations per class

{class_tbl}

`etc` rows are `iscrowd=1` ignore regions under category id
{ETC_CATEGORY_ID}, outside the queried V6 vocabulary.

## 3. Mapping, before and after

{map_tbl}

### Why `etc` is an ignore region rather than dropped or remapped

`etc` is not in V6. The ForestBelongings category-definition document defines
it as *a belonging that does not fall into the five core types* — an
out-of-vocabulary **belonging**, not background. Three options were available:

1. **Drop the boxes.** This makes a visibly annotated belonging into
   background, teaching the model that a belonging at that location is
   nothing. Rejected: the known bottleneck of this dataset is rare-class
   positive generalisation, so this is precisely the wrong signal.
2. **Remap into a V6 class.** Rejected: it fabricates a label the annotator
   explicitly declined to assign.
3. **Carry through as an `iscrowd=1` ignore region under a non-queried
   category id.** Adopted. The id is outside the caption so it never enters a
   query, and pycocotools' per-category matching never scores it against a V6
   class; detections landing on an `etc` box are neither rewarded nor
   punished.

This matches the retired system's handling (`etc_patch.py` in the research tree,
which cites the dataset's own definition document) and reuses the dataset's
existing `iscrowd=1` convention for "annotated but excluded from scoring"
rather than inventing a new one. It is an axis separate from the small-box
`iscrowd=1` regions the source already carries; those are preserved verbatim.

## 4. Evaluation set lineage

Spec §5 fixes the evaluation set at FP test + FB test pooled = **14,980
images**. The retired system's `datasets/joint_fpfbir_v3_6class/test_fp_fb.json`
had that census and V6-compatible class *names*, but it was rebuilt from
source here rather than copied, for two reasons: its category **ids** follow
the retired ordering (`gloves`=4, `bag`=5, `shoes`=6) rather than the spec §1
V6 ordering, and rebuilding leaves a direct provenance chain to
the ForestPersons `annotations/test.json` and
`datasets/ForestBelongings_v2.4/annotations/test.json`.

The rebuild was checked against the retired file: the two are **identical
box for box** — same image set, same boxes, same class names, 26,757
annotations each — with one deliberate difference. The retired builder forced
`iscrowd=0` on every non-`etc` ForestBelongings annotation, discarding the
source's own `iscrowd=1` flags on very small boxes (86 of them in the test
split). The V6 build preserves them, because `iscrowd=1` is that dataset's
convention for "annotated but excluded from scoring" and overriding it pushes
tiny ignore boxes back into the scored population. V6 test therefore carries
139 `iscrowd=1` annotations (53 `etc` + 86 source small-box flags) against
the retired file's 53. **Numbers from the retired file are not comparable to
V6 numbers** and must not be copied into a V6 table.

ForestPersonsIR is excluded from evaluation as well as training.

## 5. Verification

`utils.data.dataset_build.verify_v6_json` runs before each file is written and
rejects the file if any of the following holds:

- a singular ForestBelongings name (`cloth`/`glove`/`shoe`) or any of the 13
  ForestPersons pose subclasses survives in `categories`
- the `categories` block is not exactly the V6 six plus `etc`=7
- an annotation references a category id outside that set
- an `etc` annotation is not `iscrowd=1`
- image ids are duplicated, or an annotation points at a missing image
- the image census differs from `EXPECTED_IMAGES` for that split
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out-dir", type=Path, default=None,
                        help="defaults to the benchmark path in configs/paths.yaml")
    parser.add_argument("--splits", nargs="+", default=["train", "val", "test"])
    parser.add_argument("--doc", type=Path, default=DOC_PATH)
    args = parser.parse_args()
    # Resolved after parsing, so `--help` works before the corpora arrive.
    destination = args.out_dir or out_dir()

    reports: dict[str, SplitReport] = {}
    for split in args.splits:
        data, report = build_split(split, sources()[split])
        verify_v6_json(data, expected_images=EXPECTED_IMAGES[split])
        write_json(data, destination / f"{split}.json")
        reports[split] = report
        logger.info("%s: %d images, %d anns, %d negatives, dist=%s",
                    split, report.n_images, report.n_annotations,
                    report.n_negative_images, report.class_distribution)

    # `--doc` may point anywhere, and this write is the very last statement,
    # after every split has been built. Failing on a missing directory here
    # would throw away the whole run.
    args.doc.parent.mkdir(parents=True, exist_ok=True)
    args.doc.write_text(render_document(reports))
    logger.info("wrote %s", args.doc)


if __name__ == "__main__":
    main()
